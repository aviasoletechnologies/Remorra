import { mkdir } from "node:fs/promises";
import path from "node:path";
import puppeteer from "puppeteer";

const outputDir = path.resolve("../../output/pdf");
await mkdir(outputDir, { recursive: true });

const browser = await puppeteer.launch({ headless: true });
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 1200, height: 1600, deviceScaleFactor: 1 });
  await page.setContent(
    `<!doctype html>
    <html>
      <head>
        <meta charset="utf-8">
        <style>
          @page { size: A4; margin: 18mm; }
          * { box-sizing: border-box; }
          body { margin: 0; font-family: Arial, sans-serif; color: #17211b; background: white; }
          header { border-bottom: 3px solid #23694a; padding-bottom: 18px; margin-bottom: 24px; }
          .brand { color: #23694a; font-weight: 700; letter-spacing: 2px; font-size: 11px; }
          h1 { font-size: 28px; margin: 8px 0; }
          h2 { margin: 24px 0 8px; font-size: 17px; }
          p, li { color: #445149; font-size: 11px; line-height: 1.55; }
          .score { display: grid; grid-template-columns: 110px 1fr; gap: 18px; padding: 18px; background: #eef5ef; border-radius: 10px; }
          .number { color: #23694a; font-size: 42px; font-weight: 700; }
          table { width: 100%; border-collapse: collapse; margin-top: 12px; }
          th, td { padding: 9px; border-bottom: 1px solid #dfe3dc; text-align: left; font-size: 10px; }
          th { color: #68736b; text-transform: uppercase; font-size: 8px; letter-spacing: .08em; }
          footer { position: fixed; bottom: 0; color: #68736b; font-size: 9px; }
        </style>
      </head>
      <body>
        <header><div class="brand">REMORRA</div><h1>Product Health Report</h1><p>Northstar Workspace - generated from confirmed product and delivery evidence.</p></header>
        <section class="score"><div class="number">74</div><div><h2>Promising direction</h2><p>The product has a coherent problem and audience. Commercial evidence and measurable activation outcomes remain the strongest opportunities.</p></div></section>
        <h2>Evidence summary</h2>
        <table><thead><tr><th>Area</th><th>Signal</th><th>Finding</th></tr></thead><tbody>
          <tr><td>Problem clarity</td><td>Strong</td><td>Founder pain is specific and consistently linked to the product concept.</td></tr>
          <tr><td>Commercial evidence</td><td>Developing</td><td>Willingness to pay remains an assumption requiring direct validation.</td></tr>
          <tr><td>Delivery linkage</td><td>Healthy</td><td>Active stories retain valid parent needs and cycle context.</td></tr>
        </tbody></table>
        <h2>Priority actions</h2>
        <ol><li>Interview five target founders about current decision-tracking costs.</li><li>Define a measurable activation key result for the first product cycle.</li><li>Resolve the team invitation dependency before expanding onboarding scope.</li></ol>
        <footer>Generated by Remorra Product Intelligence</footer>
      </body>
    </html>`,
    { waitUntil: "domcontentloaded" },
  );
  await page.pdf({
    path: path.join(outputDir, "remorra-product-health-sample.pdf"),
    format: "A4",
    printBackground: true,
    margin: { top: "18mm", right: "18mm", bottom: "18mm", left: "18mm" },
  });
  await page.screenshot({
    path: path.join(outputDir, "remorra-product-health-sample.png"),
    fullPage: true,
  });
} finally {
  await browser.close();
}
